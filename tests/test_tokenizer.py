"""Tokenizer goldens vs HF tokenizers (SPEC §8). 442 cases across both models'
tokenizers, including NFC, CJK, emoji, special tokens. Fixtures generated by
oracle/m0_dump.py and tracked in tests/golden/."""
import json
import os

import pytest


def _run_golden(tok, path):
    if not os.path.exists(path):
        pytest.skip(f"{os.path.basename(path)} not present")
    cases = json.load(open(path, encoding="utf-8"))
    for c in cases:
        ids = tok.encode(c["text"])
        assert ids == c["ids"], f"encode {c['text']!r}: {ids} != {c['ids']}"
        assert tok.decode(ids) == c["decoded"], f"decode {c['text']!r}"


def test_golden_4b(tok4b, golden_dir):
    _run_golden(tok4b, os.path.join(golden_dir, "golden.json"))


def test_golden_random(tok4b, golden_dir):
    _run_golden(tok4b, os.path.join(golden_dir, "golden_random.json"))


def test_golden_27b(tok27b, golden_dir):
    _run_golden(tok27b, os.path.join(golden_dir, "golden_27b.json"))


def test_special_tokens_literal(tok4b):
    ids = tok4b.encode("<|im_start|>user\nhi<|im_end|>")
    assert ids[0] == 248045 and ids[-1] == 248046  # im_start / im_end


def test_no_bos(tok4b):
    assert tok4b.encode("Hello") == tok4b.encode("Hello")  # stable, no BOS prepended
    assert tok4b.encode("")[0:0] == []
